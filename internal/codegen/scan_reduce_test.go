	// Non-identity: soft_mux(0.5, soft_mux(0.5,20,4), soft_mux(0.5, soft_mux(0.5,20,4), 4))
	// wn = 0.5*0.5 + 0.5*0.5*0.5 = 0.25+0.125=0.375 → y=0.375*20+0.625*4=7.5+2.5=10
