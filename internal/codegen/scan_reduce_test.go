func TestRewriteDeepForestFold(t *testing.T) {
	// Use non-identity weights so strength/w=0,1 do not fire first.
	// soft_mux(0.5, soft_mux(0.5, soft_mux(0.5, soft_mux(0.5,20,4), 4), 4), soft_mux(0.25,20,4))
	// pure nest product: 0.5^3 = 0.125 after stepwise (or deep wn = 0.5*0.5*0.5*0.5 + 0.5*0.25
	//   = 0.0625+0.125 = 0.1875 → y = 0.1875*20 + 0.8125*4 = 3.75+3.25 = 7)
	mlir := `
module attributes {trin.version = "0.40"} {
  func.func @trin_soft_mux(%w: f32, %p: f32, %e: f32) -> f32 { return %p : f32 }
  func.func @probe() -> f32 {
    %w = arith.constant 5.000000e-01 : f32
    %w2 = arith.constant 5.000000e-01 : f32
    %w3 = arith.constant 5.000000e-01 : f32
    %w4 = arith.constant 5.000000e-01 : f32
    %w5 = arith.constant 2.500000e-01 : f32
    %p = arith.constant 2.000000e+01 : f32
    %e = arith.constant 4.000000e+00 : f32
    %leaf = func.call @trin_soft_mux(%w4, %p, %e) : (f32, f32, f32) -> f32
    %m1 = func.call @trin_soft_mux(%w3, %leaf, %e) : (f32, f32, f32) -> f32
    %m2 = func.call @trin_soft_mux(%w2, %m1, %e) : (f32, f32, f32) -> f32
    %arm = func.call @trin_soft_mux(%w5, %p, %e) : (f32, f32, f32) -> f32
    %y = func.call @trin_soft_mux(%w, %m2, %arm) : (f32, f32, f32) -> f32
    return %y : f32
  }
}
`
	out, err := RewriteMLIR(mlir)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(out, `trin.version = "0.81"`) {
		t.Fatalf("missing version 0.81:\n%s", out)
	}
	// Prefer dedicated deep-forest note, but stepwise product also yields 7.
	if !strings.Contains(out, "7.000000e+00") {
		t.Fatalf("expected deep forest algebra → 7:\n%s", out)
	}
	if !strings.Contains(out, "soft_mux deep forest") &&
		!strings.Contains(out, "soft_mux forest product both-arms") &&
		!strings.Contains(out, "soft_mux(w1, soft_mux(w2,p,e), e)") {
		t.Fatalf("expected some forest/nest fold note:\n%s", out)
	}
}

