// LLVMHostDriver returns a small C main that probes a pure float kernel exported
// by EmitLLVM. Used by `trin link-llvm` / `trin build --backend llvm`.
// When the module already defines @main (full-program lowering, v0.19), returns ""
// so the object file's own main is used without a second host driver.
func LLVMHostDriver(entry, ll string) string {
	if hasLLVMMain(ll) {
		return ""
	}
	if entry == "" {
		entry = "trin_soft_mux"
	}
	// Discover arity from "define float @entry(" line when present.
	arity := llvmFnArity(ll, entry)
	// Nullary float probes (e.g. trin_vec_loop_probe) have arity 0.
	if arity == 0 && strings.Contains(ll, "define float @"+entry+"(") {
		var b strings.Builder
		b.WriteString("/* Generated by Trin link-llvm host driver */\n")
		b.WriteString("#include <stdio.h>\n")
		fmt.Fprintf(&b, "float %s(void);\n", entry)
		fmt.Fprintf(&b, "int main(void){\n  float y = %s();\n", entry)
		fmt.Fprintf(&b, "  printf(\"llvm entry %s = %%.1f\\n\", y);\n", entry)
		b.WriteString("  return 0;\n}\n")
		return b.String()
	}
	var b strings.Builder
	b.WriteString("/* Generated by Trin link-llvm host driver */\n")
	b.WriteString("#include <stdio.h>\n")
	switch arity {
	case 1:
		fmt.Fprintf(&b, "float %s(float a0);\n", entry)
		fmt.Fprintf(&b, "int main(void){\n  float y = %s(1.0f);\n", entry)
	case 2:
		fmt.Fprintf(&b, "float %s(float a0, float a1);\n", entry)
		fmt.Fprintf(&b, "int main(void){\n  float y = %s(1.0f, 2.0f);\n", entry)
	case 3:
		fmt.Fprintf(&b, "float %s(float a0, float a1, float a2);\n", entry)
		// soft_mux probe: soft_mux(0.25, 10, 2) = 4.0
		if entry == "trin_soft_mux" {
			fmt.Fprintf(&b, "int main(void){\n  float y = %s(0.25f, 10.0f, 2.0f);\n", entry)
		} else {
			fmt.Fprintf(&b, "int main(void){\n  float y = %s(0.5f, 3.0f, 2.0f);\n", entry)
		}
	case 4:
		fmt.Fprintf(&b, "float %s(float a0, float a1, float a2, float a3);\n", entry)
		// loss(w,a,x,b) = soft_mux(w, a*x, b): loss(0.5,3,4,2)=7
		fmt.Fprintf(&b, "int main(void){\n  float y = %s(0.5f, 3.0f, 4.0f, 2.0f);\n", entry)
	default:
		// Fallback: soft_mux-style if we cannot parse.
		if entry == "trin_soft_mux" || arity <= 0 {
			fmt.Fprintf(&b, "float %s(float w, float pure, float each);\n", entry)
			fmt.Fprintf(&b, "int main(void){\n  float y = %s(0.25f, 10.0f, 2.0f);\n", entry)
		} else {
			// call with zeros via a loose prototype (may mis-ABI — avoid when possible)
			fmt.Fprintf(&b, "float %s(float a0, float a1, float a2, float a3);\n", entry)
			fmt.Fprintf(&b, "int main(void){\n  float y = %s(0.5f, 3.0f, 4.0f, 2.0f);\n", entry)
		}
	}
	fmt.Fprintf(&b, "  printf(\"llvm entry %s = %%.1f\\n\", y);\n", entry)
	b.WriteString("  return 0;\n}\n")
	return b.String()
}

func llvmFnArity(ll, name string) int {
	needle := "define float @" + name + "("
	i := strings.Index(ll, needle)
	if i < 0 {
		return -1
	}
	rest := ll[i+len(needle):]
	j := strings.Index(rest, ")")
	if j < 0 {
		return -1
	}
	params := strings.TrimSpace(rest[:j])
	if params == "" {
		return 0
	}
	// count commas + 1 among float params
	n := 1
	for _, c := range params {
		if c == ',' {
			n++
		}
	}
	return n
}

// EmitLLVM lowers a Trin program to LLVM IR text (float kernels + soft_mux).
func EmitLLVM(prog *ast.Program) (string, error) {
	mod, err := ir.Emit(prog)
	if err != nil {
		return "", err
	}
	return EmitLLVMModule(mod, prog)
}

// EmitLLVMModule dumps a TrinIR module as LLVM IR text.
// pure f32 graph functions get a proper SSA float path when possible;
// otherwise instrs become commented outlines under a stub main.
func EmitLLVMModule(mod *ir.Module, prog *ast.Program) (string, error) {
	var b strings.Builder
	b.WriteString("; Generated by Trin v0.20 emit-llvm (text; link via trin link-llvm / --backend llvm)\n")
	b.WriteString("target datalayout = \"e-m:e-p270:32:32-p271:32:32-p272:64:64-i64:64-f80:128-n8:16:32:64-S128\"\n")
	b.WriteString("target triple = \"x86_64-unknown-linux-gnu\"\n\n")
	b.WriteString("; soft_mux(w, pure, each) = w*pure + (1-w)*each\n")
	b.WriteString("define float @trin_soft_mux(float %w, float %pure, float %each) {\n")
	b.WriteString("entry:\n")
	b.WriteString("  %one = fsub float 1.000000e+00, %w\n")
	b.WriteString("  %t0 = fmul float %w, %pure\n")
	b.WriteString("  %t1 = fmul float %one, %each\n")
	b.WriteString("  %y = fadd float %t0, %t1\n")
	b.WriteString("  ret float %y\n")
	b.WriteString("}\n\n")
	// f32 sum of 4 + f32 dot of 4 (inline helper kernels used by demos)
	b.WriteString("define float @trin_sum4(float %a0, float %a1, float %a2, float %a3) {\n")
	b.WriteString("entry:\n")
	b.WriteString("  %s0 = fadd float %a0, %a1\n")
	b.WriteString("  %s1 = fadd float %s0, %a2\n")
	b.WriteString("  %s2 = fadd float %s1, %a3\n")
	b.WriteString("  ret float %s2\n")
	b.WriteString("}\n\n")
	b.WriteString("define float @trin_dot4(float %a0, float %a1, float %a2, float %a3, float %b0, float %b1, float %b2, float %b3) {\n")
	b.WriteString("entry:\n")
	b.WriteString("  %p0 = fmul float %a0, %b0\n")
	b.WriteString("  %p1 = fmul float %a1, %b1\n")
	b.WriteString("  %p2 = fmul float %a2, %b2\n")
	b.WriteString("  %p3 = fmul float %a3, %b3\n")
	b.WriteString("  %s0 = fadd float %p0, %p1\n")
	b.WriteString("  %s1 = fadd float %s0, %p2\n")
	b.WriteString("  %s2 = fadd float %s1, %p3\n")
	b.WriteString("  ret float %s2\n")
	b.WriteString("}\n\n")

	b.WriteString("define float @trin_sum_span_add4(float %a0, float %a1, float %a2, float %a3, float %b0, float %b1, float %b2, float %b3) {\n")
	b.WriteString("entry:\n")
	b.WriteString("  %z0 = fadd float %a0, %b0\n")
	b.WriteString("  %z1 = fadd float %a1, %b1\n")
	b.WriteString("  %z2 = fadd float %a2, %b2\n")
	b.WriteString("  %z3 = fadd float %a3, %b3\n")
	b.WriteString("  %s0 = fadd float %z0, %z1\n")
	b.WriteString("  %s1 = fadd float %s0, %z2\n")
	b.WriteString("  %s2 = fadd float %s1, %z3\n")
	b.WriteString("  ret float %s2\n")
	b.WriteString("}\n\n")
	b.WriteString("define float @trin_sum_map_mul4(float %s, float %x0, float %x1, float %x2, float %x3) {\n")
	b.WriteString("entry:\n")
	b.WriteString("  %p0 = fmul float %s, %x0\n")
	b.WriteString("  %p1 = fmul float %s, %x1\n")
	b.WriteString("  %p2 = fmul float %s, %x2\n")
	b.WriteString("  %p3 = fmul float %s, %x3\n")
	b.WriteString("  %t0 = fadd float %p0, %p1\n")
	b.WriteString("  %t1 = fadd float %t0, %p2\n")
	b.WriteString("  %t2 = fadd float %t1, %p3\n")
	b.WriteString("  ret float %t2\n")
	b.WriteString("}\n\n")
	// Variable-length span kernels with auto residual peel (v0.36; was v0.20 loops).
	// Full-program path later embeds real CPUID @trin_hw_vlen_for_n (v0.30/v0.32),
	// so do not inject a portable fallback here — that would redefine the symbol.
	// Standalone float modules without @main still get a portable define via the
	// post-pass ensurePeelHWVLEN on the final buffer (see end of EmitLLVMModule).
	b.WriteString(emitLLVMSpanLoopHelpers())
	// Dense trit bitplane helpers (SIMD-friendly 32-lane words, v0.16/0.17)
	b.WriteString("; trit bitplane product over one i32 word pair: popcount(pos)-popcount(neg)\n")
	b.WriteString("define i32 @trin_trit_dot_planes_word(i32 %ap, i32 %an, i32 %bp, i32 %bn) {\n")
	b.WriteString("entry:\n")
	b.WriteString("  %t0 = and i32 %ap, %bp\n")
	b.WriteString("  %t1 = and i32 %an, %bn\n")
	b.WriteString("  %pos = or i32 %t0, %t1\n")
	b.WriteString("  %t2 = and i32 %ap, %bn\n")
	b.WriteString("  %t3 = and i32 %an, %bp\n")
	b.WriteString("  %neg = or i32 %t2, %t3\n")
	b.WriteString("  %pcp = call i32 @llvm.ctpop.i32(i32 %pos)\n")
	b.WriteString("  %pcn = call i32 @llvm.ctpop.i32(i32 %neg)\n")
	b.WriteString("  %y = sub i32 %pcp, %pcn\n")
	b.WriteString("  ret i32 %y\n")
	b.WriteString("}\n\n")
	b.WriteString("declare i32 @llvm.ctpop.i32(i32)\n\n")
	b.WriteString("define i32 @trin_plane_and(i32 %a, i32 %b) {\n")
	b.WriteString("entry:\n")
	b.WriteString("  %y = and i32 %a, %b\n")
	b.WriteString("  ret i32 %y\n")
	b.WriteString("}\n\n")
	b.WriteString("define i32 @trin_plane_or(i32 %a, i32 %b) {\n")
	b.WriteString("entry:\n")
	b.WriteString("  %y = or i32 %a, %b\n")
	b.WriteString("  ret i32 %y\n")
	b.WriteString("}\n\n")
	b.WriteString("define i32 @trin_plane_xor(i32 %a, i32 %b) {\n")
	b.WriteString("entry:\n")
	b.WriteString("  %y = xor i32 %a, %b\n")
	b.WriteString("  ret i32 %y\n")
	b.WriteString("}\n\n")
	b.WriteString("define i32 @trin_plane_popcount(i32 %w) {\n")
	b.WriteString("entry:\n")
	b.WriteString("  %y = call i32 @llvm.ctpop.i32(i32 %w)\n")
	b.WriteString("  ret i32 %y\n")
	b.WriteString("}\n\n")
	// 128-lane multiword helper: 4×i32 word product unrolled (v0.18 SIMD surface)
	b.WriteString("; sum of four trin_trit_dot_planes_word calls — 128-lane chunk\n")
	b.WriteString("define i32 @trin_trit_dot_planes_x4(i32 %ap0, i32 %an0, i32 %bp0, i32 %bn0,\n")
	b.WriteString("                                    i32 %ap1, i32 %an1, i32 %bp1, i32 %bn1,\n")
	b.WriteString("                                    i32 %ap2, i32 %an2, i32 %bp2, i32 %bn2,\n")
	b.WriteString("                                    i32 %ap3, i32 %an3, i32 %bp3, i32 %bn3) {\n")
	b.WriteString("entry:\n")
	b.WriteString("  %d0 = call i32 @trin_trit_dot_planes_word(i32 %ap0, i32 %an0, i32 %bp0, i32 %bn0)\n")
	b.WriteString("  %d1 = call i32 @trin_trit_dot_planes_word(i32 %ap1, i32 %an1, i32 %bp1, i32 %bn1)\n")
	b.WriteString("  %d2 = call i32 @trin_trit_dot_planes_word(i32 %ap2, i32 %an2, i32 %bp2, i32 %bn2)\n")
	b.WriteString("  %d3 = call i32 @trin_trit_dot_planes_word(i32 %ap3, i32 %an3, i32 %bp3, i32 %bn3)\n")
	b.WriteString("  %s0 = add i32 %d0, %d1\n")
	b.WriteString("  %s1 = add i32 %s0, %d2\n")
	b.WriteString("  %y = add i32 %s1, %d3\n")
	b.WriteString("  ret i32 %y\n")
	b.WriteString("}\n\n")
	b.WriteString("define i32 @trin_simd_lane_width() {\n")
	b.WriteString("entry:\n")
	b.WriteString("  ret i32 128\n")
	b.WriteString("}\n\n")
	// Prefer direct kernel emission from main when it looks like a pure f32 demo
	if prog != nil {
		k := tryFloatKernel(prog)
		if k != "" {
			b.WriteString(k)
		}
		// Full-program lowering (v0.19): runnable @main with println/to_str/spans/i32.
		// Skip when a pure float export (loss/kernel) is present so the float host driver
		// keeps working for soft_kernel / link-llvm demos. Programs without those exports
		// (hello, full_prog demos) get a real @main in the object file.
		hasHostKernel := strings.Contains(k, "define float @loss(") ||
			strings.Contains(k, "define float @kernel(") ||
			strings.Contains(k, "define float @soft_kernel(")
		if !hasHostKernel {
			if full := emitFullProgram(prog); full != "" {
				b.WriteString("\n")
				b.WriteString(full)
			}
		}
		b.WriteString("\n; --- TrinIR dump (reference) ---\n")
		for _, line := range strings.Split(mod.String(), "\n") {
			if line == "" {
				continue
			}
			b.WriteString("; ")
			b.WriteString(line)
			b.WriteByte('\n')
		}
		if k != "" || hasLLVMMain(b.String()) {
			return ensurePeelHWVLEN(b.String()), nil
		}
	}

	// Generic: map each TrinIR func to a float stub + comment body
	for _, fn := range mod.Funcs {
		fmt.Fprintf(&b, "define float @%s(", sanitizeLLVM(fn.Name))
		for i, p := range fn.Params {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "float %%%s", sanitizeLLVM(p))
		}
		b.WriteString(") {\nentry:\n")
		// lower instructions best-effort for f32 arithmetic
		vals := map[string]string{}
		for _, p := range fn.Params {
			vals[p] = "%" + sanitizeLLVM(p)
		}
		nTmp := 0
		fresh := func() string {
			nTmp++
			return fmt.Sprintf("%%t%d", nTmp)
		}
		last := "0.000000e+00"
		for _, in := range fn.Body {
			switch in.Op {
			case ir.OpConstF32, ir.OpConstUnit:
				dst := fresh()
				fmt.Fprintf(&b, "  %s = fadd float %s, 0.000000e+00 ; const %g\n", dst, llvmF32(in.F64), in.F64)
				if in.Dst != nil {
					vals[in.Dst.Name] = dst
				}
				last = dst
			case ir.OpConstI32, ir.OpConstBit:
				dst := fresh()
				fmt.Fprintf(&b, "  %s = sitofp i32 %d to float\n", dst, in.I64)
				if in.Dst != nil {
					vals[in.Dst.Name] = dst
				}
				last = dst
			case ir.OpAdd, ir.OpSub, ir.OpMul, ir.OpDiv:
				if len(in.Args) < 2 {
					continue
				}
				la := lookup(vals, in.Args[0].Name)
				ra := lookup(vals, in.Args[1].Name)
				dst := fresh()
				op := "fadd"
				switch in.Op {
				case ir.OpSub:
					op = "fsub"
				case ir.OpMul:
					op = "fmul"
				case ir.OpDiv:
					op = "fdiv"
				}
				fmt.Fprintf(&b, "  %s = %s float %s, %s\n", dst, op, la, ra)
				if in.Dst != nil {
					vals[in.Dst.Name] = dst
				}
				last = dst
			case ir.OpSoftMux:
				if len(in.Args) < 3 {
					continue
				}
				w := lookup(vals, in.Args[0].Name)
				p := lookup(vals, in.Args[1].Name)
				e := lookup(vals, in.Args[2].Name)
				dst := fresh()
				fmt.Fprintf(&b, "  %s = call float @trin_soft_mux(float %s, float %s, float %s)\n", dst, w, p, e)
				if in.Dst != nil {
					vals[in.Dst.Name] = dst
				}
				last = dst
			case ir.OpUnaryNeg:
				if len(in.Args) < 1 {
					continue
				}
				x := lookup(vals, in.Args[0].Name)
				dst := fresh()
				fmt.Fprintf(&b, "  %s = fneg float %s\n", dst, x)
				if in.Dst != nil {
					vals[in.Dst.Name] = dst
				}
				last = dst
			case ir.OpRet:
				if len(in.Args) > 0 {
					last = lookup(vals, in.Args[0].Name)
				}
				fmt.Fprintf(&b, "  ret float %s\n", last)
			case ir.OpLoad:
				// treat load of known param
				if in.Dst != nil {
					if v, ok := vals[in.Meta]; ok {
						vals[in.Dst.Name] = v
					} else {
						dst := fresh()
						fmt.Fprintf(&b, "  %s = fadd float 0.000000e+00, 0.000000e+00 ; load %s\n", dst, in.Meta)
						vals[in.Dst.Name] = dst
						last = dst
					}
				}
			case ir.OpStore:
				// ignore stores in pure float kernels
			case ir.OpCall:
				// opaque calls → 0
				dst := fresh()
				fmt.Fprintf(&b, "  %s = fadd float 0.000000e+00, 0.000000e+00 ; call @%s\n", dst, in.Meta)
				if in.Dst != nil {
					vals[in.Dst.Name] = dst
				}
				last = dst
			default:
				fmt.Fprintf(&b, "  ; unhandled %s\n", in.Op)
			}
		}
		// ensure ret if missing
		if !strings.Contains(b.String()[strings.LastIndex(b.String(), "define"):], "ret float") {
			fmt.Fprintf(&b, "  ret float %s\n", last)
		}
		b.WriteString("}\n\n")
	}
	return ensurePeelHWVLEN(b.String()), nil
}

func lookup(vals map[string]string, name string) string {
	if v, ok := vals[name]; ok {
		return v
	}
	return "0.000000e+00"
}

func llvmF32(f float64) string {
	// use scientific float for LLVM
	return strconv.FormatFloat(f, 'e', 6, 64)
}

func sanitizeLLVM(s string) string {
	var b strings.Builder
	for _, r := range s {
		if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') || r == '_' {
			b.WriteRune(r)
		} else {
			b.WriteByte('_')
		}
	}
	out := b.String()
	if out == "" {
		return "x"
	}
	return out
}

// tryFloatKernel: if program has fn kernel(...)->f32-like pure soft_mux graph named soft_kernel, emit it.
func tryFloatKernel(prog *ast.Program) string {
	var kn *ast.FnDef
	for _, it := range prog.Items {
		if fn, ok := it.(*ast.FnDef); ok && (fn.Name == "kernel" || fn.Name == "soft_kernel") {
			kn = fn
			break
		}
	}
	if kn == nil {
		// also emit soft_mux helpers + a demo function from main body analysis
		return emitDemoFromSoftMuxGradLike(prog)
	}
	return emitPureFn(kn)
}

func emitPureFn(fn *ast.FnDef) string {
	var b strings.Builder
	fmt.Fprintf(&b, "define float @%s(", sanitizeLLVM(fn.Name))
	for i, p := range fn.Params {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "float %%%s", sanitizeLLVM(p.Name))
	}
	b.WriteString(") {\nentry:\n")
	g := &llbuilder{b: &b, names: map[string]string{}, n: 0}
	for _, p := range fn.Params {
		g.names[p.Name] = "%" + sanitizeLLVM(p.Name)
	}
	if fn.Body == nil {
		b.WriteString("  ret float 0.000000e+00\n}\n")
		return b.String()
	}
	// only last expression / return
	for _, st := range fn.Body.Stmts {
		if ls, ok := st.(*ast.LetStmt); ok {
			v, err := g.emit(ls.Value)
			if err != nil {
				b.WriteString("  ; " + err.Error() + "\n")
				continue
			}
			g.names[ls.Name] = v
		}
		if rs, ok := st.(*ast.ReturnStmt); ok && rs.Value != nil {
			v, err := g.emit(rs.Value)
			if err != nil {
				fmt.Fprintf(&b, "  ret float 0.000000e+00 ; err %v\n}\n", err)
				return b.String()
			}
			fmt.Fprintf(&b, "  ret float %s\n}\n", v)
			return b.String()
		}
	}
	if fn.Body.Expr != nil {
		v, err := g.emit(fn.Body.Expr)
		if err != nil {
			fmt.Fprintf(&b, "  ret float 0.000000e+00 ; err %v\n}\n", err)
			return b.String()
		}
		fmt.Fprintf(&b, "  ret float %s\n}\n", v)
		return b.String()
	}
	b.WriteString("  ret float 0.000000e+00\n}\n")
	return b.String()
}

type llbuilder struct {
	b     *strings.Builder
	names map[string]string
	n     int
}

func (g *llbuilder) fresh() string {
	g.n++
	return fmt.Sprintf("%%v%d", g.n)
}

func (g *llbuilder) emit(e ast.Expr) (string, error) {
	switch n := e.(type) {
	case *ast.Literal:
		dst := g.fresh()
		var f float64
		switch n.Kind {
		case "int":
			f = float64(n.Value.(int))
		case "float":
			f = n.Value.(float64)
		case "bool":
			if n.Value.(bool) {
				f = 1
			}
		}
		fmt.Fprintf(g.b, "  %s = fadd float %s, 0.000000e+00\n", dst, llvmF32(f))
		return dst, nil
	case *ast.Var:
		if v, ok := g.names[n.Name]; ok {
			return v, nil
		}
		return "", fmt.Errorf("unknown %s", n.Name)
	case *ast.Unary:
		x, err := g.emit(n.Expr)
		if err != nil {
			return "", err
		}
		if n.Op == "-" {
			dst := g.fresh()
			fmt.Fprintf(g.b, "  %s = fneg float %s\n", dst, x)
			return dst, nil
		}
		return x, nil
	case *ast.Binary:
		l, err := g.emit(n.Left)
		if err != nil {
			return "", err
		}
		r, err := g.emit(n.Right)
		if err != nil {
			return "", err
		}
		op := "fadd"
		switch n.Op {
		case "-":
			op = "fsub"
		case "*":
			op = "fmul"
		case "/":
			op = "fdiv"
		case "+":
			op = "fadd"
		default:
			return "", fmt.Errorf("op %s", n.Op)
		}
		dst := g.fresh()
		fmt.Fprintf(g.b, "  %s = %s float %s, %s\n", dst, op, l, r)
		return dst, nil
	case *ast.Ternary:
		w, err := g.emit(n.Gate)
		if err != nil {
			return "", err
		}
		p, err := g.emit(n.Pure)
		if err != nil {
			return "", err
		}
		ea, err := g.emit(n.Each)
		if err != nil {
			return "", err
		}
		dst := g.fresh()
		fmt.Fprintf(g.b, "  %s = call float @trin_soft_mux(float %s, float %s, float %s)\n", dst, w, p, ea)
		return dst, nil
	case *ast.Call:
		v, ok := n.Callee.(*ast.Var)
		if !ok {
			return "", fmt.Errorf("call")
		}
		switch v.Name {
		case "soft_mux":
			if len(n.Args) != 3 {
				return "", fmt.Errorf("soft_mux arity")
			}
			w, err := g.emit(n.Args[0])
			if err != nil {
				return "", err
			}
			p, err := g.emit(n.Args[1])
			if err != nil {
				return "", err
			}
			ea, err := g.emit(n.Args[2])
			if err != nil {
				return "", err
			}
			dst := g.fresh()
			fmt.Fprintf(g.b, "  %s = call float @trin_soft_mux(float %s, float %s, float %s)\n", dst, w, p, ea)
			return dst, nil
		case "sum":
			// sum of scalar args or one span-like not representable — chain fadd of emitted args
			if len(n.Args) == 0 {
				return "", fmt.Errorf("sum empty")
			}
			// If single span literal: fold elements
			if len(n.Args) == 1 {
				if sl, ok := n.Args[0].(*ast.SpanLit); ok {
					return g.emitSumElems(sl.Elems)
				}
				if call, ok := n.Args[0].(*ast.Call); ok {
					return g.emitSpanProducerThenSum(call)
				}
			}
			return g.emitSumElems(n.Args)
		case "dot":
			if len(n.Args) != 2 {
				return "", fmt.Errorf("dot arity")
			}
			sla, oka := n.Args[0].(*ast.SpanLit)
			slb, okb := n.Args[1].(*ast.SpanLit)
			if !oka || !okb {
				return "", fmt.Errorf("dot wants span lits")
			}
			nlen := len(sla.Elems)
			if len(slb.Elems) < nlen {
				nlen = len(slb.Elems)
			}
			if nlen == 0 {
				dst := g.fresh()
				fmt.Fprintf(g.b, "  %s = fadd float 0.000000e+00, 0.000000e+00\n", dst)
				return dst, nil
			}
			var acc string
			for i := 0; i < nlen; i++ {
				ai, err := g.emit(sla.Elems[i])
				if err != nil {
					return "", err
				}
				bi, err := g.emit(slb.Elems[i])
				if err != nil {
					return "", err
				}
				prod := g.fresh()
				fmt.Fprintf(g.b, "  %s = fmul float %s, %s\n", prod, ai, bi)
				if i == 0 {
					acc = prod
				} else {
					nxt := g.fresh()
					fmt.Fprintf(g.b, "  %s = fadd float %s, %s\n", nxt, acc, prod)
					acc = nxt
				}
			}
			return acc, nil
		}
		return "", fmt.Errorf("unsupported call %s", v.Name)
	default:
		return "", fmt.Errorf("unsupported %T", e)
	}
}


func (g *llbuilder) emitSpanProducerThenSum(n *ast.Call) (string, error) {
	v, ok := n.Callee.(*ast.Var)
	if !ok {
		return "", fmt.Errorf("span call")
	}
	switch v.Name {
	case "span_add":
		if len(n.Args) != 2 {
			return "", fmt.Errorf("span_add arity")
		}
		as, err := g.emitSpanElems(n.Args[0])
		if err != nil {
			return "", err
		}
		bs, err := g.emitSpanElems(n.Args[1])
		if err != nil {
			return "", err
		}
		nn := len(as)
		if len(bs) < nn {
			nn = len(bs)
		}
		elems := make([]string, nn)
		for i := 0; i < nn; i++ {
			dst := g.fresh()
			fmt.Fprintf(g.b, "  %s = fadd float %s, %s\n", dst, as[i], bs[i])
			elems[i] = dst
		}
		return g.emitSumSSA(elems)
	case "scale", "map_mul":
		if len(n.Args) != 2 {
			return "", fmt.Errorf("%s arity", v.Name)
		}
		sid, err := g.emit(n.Args[0])
		if err != nil {
			return "", err
		}
		xs, err := g.emitSpanElems(n.Args[1])
		if err != nil {
			return "", err
		}
		elems := make([]string, len(xs))
		for i, x := range xs {
			dst := g.fresh()
			fmt.Fprintf(g.b, "  %s = fmul float %s, %s\n", dst, sid, x)
			elems[i] = dst
		}
		return g.emitSumSSA(elems)
	case "map":
		// map((x)=>body, span) — emit body per element with param bound
		if len(n.Args) != 2 {
			return "", fmt.Errorf("map arity")
		}
		lam, ok := n.Args[0].(*ast.Lambda)
		if !ok || len(lam.Params) != 1 {
			return "", fmt.Errorf("map wants unary lambda")
		}
		xs, err := g.emitSpanElems(n.Args[1])
		if err != nil {
			return "", err
		}
		elems := make([]string, len(xs))
		pname := lam.Params[0].Name
		for i, x := range xs {
			saved := g.names[pname]
			g.names[pname] = x
			v, err := g.emit(lam.Body)
			if saved != "" {
				g.names[pname] = saved
			} else {
				delete(g.names, pname)
			}
			if err != nil {
				return "", err
			}
			elems[i] = v
		}
		return g.emitSumSSA(elems)
	default:
		return "", fmt.Errorf("unsupported span producer %s", v.Name)
	}
}

func (g *llbuilder) emitSpanElems(e ast.Expr) ([]string, error) {
	switch n := e.(type) {
	case *ast.SpanLit:
		out := make([]string, len(n.Elems))
		for i, el := range n.Elems {
			v, err := g.emit(el)
			if err != nil {
				return nil, err
			}
			out[i] = v
		}
		return out, nil
	case *ast.Call:
		v, ok := n.Callee.(*ast.Var)
		if !ok {
			return nil, fmt.Errorf("span call")
		}
		switch v.Name {
		case "span_add":
			if len(n.Args) != 2 {
				return nil, fmt.Errorf("span_add arity")
			}
			as, err := g.emitSpanElems(n.Args[0])
			if err != nil {
				return nil, err
			}
			bs, err := g.emitSpanElems(n.Args[1])
			if err != nil {
				return nil, err
			}
			nn := len(as)
			if len(bs) < nn {
				nn = len(bs)
			}
			out := make([]string, nn)
			for i := 0; i < nn; i++ {
				dst := g.fresh()
				fmt.Fprintf(g.b, "  %s = fadd float %s, %s\n", dst, as[i], bs[i])
				out[i] = dst
			}
			return out, nil
		case "scale", "map_mul":
			if len(n.Args) != 2 {
				return nil, fmt.Errorf("%s arity", v.Name)
			}
			sid, err := g.emit(n.Args[0])
			if err != nil {
				return nil, err
			}
			xs, err := g.emitSpanElems(n.Args[1])
			if err != nil {
				return nil, err
			}
			out := make([]string, len(xs))
			for i, x := range xs {
				dst := g.fresh()
				fmt.Fprintf(g.b, "  %s = fmul float %s, %s\n", dst, sid, x)
				out[i] = dst
			}
			return out, nil
		case "map":
			if len(n.Args) != 2 {
				return nil, fmt.Errorf("map arity")
			}
			lam, ok := n.Args[0].(*ast.Lambda)
			if !ok || len(lam.Params) != 1 {
				return nil, fmt.Errorf("map wants unary lambda")
			}
			xs, err := g.emitSpanElems(n.Args[1])
			if err != nil {
				return nil, err
			}
			out := make([]string, len(xs))
			pname := lam.Params[0].Name
			for i, x := range xs {
				saved := g.names[pname]
				g.names[pname] = x
				vv, err := g.emit(lam.Body)
				if saved != "" {
					g.names[pname] = saved
				} else {
					delete(g.names, pname)
				}
				if err != nil {
					return nil, err
				}
				out[i] = vv
			}
			return out, nil
		default:
			return nil, fmt.Errorf("unsupported nested span producer %s", v.Name)
		}
	default:
		return nil, fmt.Errorf("span lit or producer expected")
	}
}

func (g *llbuilder) emitSumSSA(elems []string) (string, error) {
	if len(elems) == 0 {
		dst := g.fresh()
		fmt.Fprintf(g.b, "  %s = fadd float 0.000000e+00, 0.000000e+00\n", dst)
		return dst, nil
	}
	acc := elems[0]
	for i := 1; i < len(elems); i++ {
		nxt := g.fresh()
		fmt.Fprintf(g.b, "  %s = fadd float %s, %s\n", nxt, acc, elems[i])
		acc = nxt
	}
	return acc, nil
}

func (g *llbuilder) emitSumElems(elems []ast.Expr) (string, error) {
	if len(elems) == 0 {
		dst := g.fresh()
		fmt.Fprintf(g.b, "  %s = fadd float 0.000000e+00, 0.000000e+00\n", dst)
		return dst, nil
	}
	acc, err := g.emit(elems[0])
	if err != nil {
		return "", err
	}
	for i := 1; i < len(elems); i++ {
		x, err := g.emit(elems[i])
		if err != nil {
			return "", err
		}
		nxt := g.fresh()
		fmt.Fprintf(g.b, "  %s = fadd float %s, %s\n", nxt, acc, x)
		acc = nxt
	}
	return acc, nil
}

func emitDemoFromSoftMuxGradLike(prog *ast.Program) string {
	// Always emit a reference kernel used by AD demos:
	// float @trin_demo_kernel(float %w, float %a, float %x, float %b)
	//   ret soft_mux(w, a*x, b)
	var b strings.Builder
	b.WriteString("define float @trin_demo_kernel(float %w, float %a, float %x, float %b) {\n")
	b.WriteString("entry:\n")
	b.WriteString("  %pure = fmul float %a, %x\n")
	b.WriteString("  %y = call float @trin_soft_mux(float %w, float %pure, float %b)\n")
	b.WriteString("  ret float %y\n")
	b.WriteString("}\n\n")
	// span kernel demo: soft_mux(w, sum4, dot4)
	b.WriteString("define float @trin_span_mix(float %w, float %a0, float %a1, float %a2, float %a3, float %b0, float %b1, float %b2, float %b3) {\n")
	b.WriteString("entry:\n")
	b.WriteString("  %s = call float @trin_sum4(float %a0, float %a1, float %a2, float %a3)\n")
	b.WriteString("  %d = call float @trin_dot4(float %a0, float %a1, float %a2, float %a3, float %b0, float %b1, float %b2, float %b3)\n")
	b.WriteString("  %y = call float @trin_soft_mux(float %w, float %s, float %d)\n")
	b.WriteString("  ret float %y\n")
	b.WriteString("}\n\n")
		b.WriteString("define float @trin_map_span_mix(float %w, float %s, float %a0, float %a1, float %a2, float %a3, float %b0, float %b1, float %b2, float %b3, float %x0, float %x1, float %x2, float %x3) {\n")
	b.WriteString("entry:\n")
	b.WriteString("  %add = call float @trin_sum_span_add4(float %a0, float %a1, float %a2, float %a3, float %b0, float %b1, float %b2, float %b3)\n")
	b.WriteString("  %mm = call float @trin_sum_map_mul4(float %s, float %x0, float %x1, float %x2, float %x3)\n")
	b.WriteString("  %y = call float @trin_soft_mux(float %w, float %add, float %mm)\n")
	b.WriteString("  ret float %y\n")
	b.WriteString("}\n\n")
	b.WriteString("define float @trin_map_lambda_mix(float %w, float %a, float %p, float %q, float %b, float %r) {\n")
	b.WriteString("entry:\n")
	b.WriteString("  %mp0 = fmul float %p, %a\n")
	b.WriteString("  %mp1 = fmul float %q, %a\n")
	b.WriteString("  %pure = fadd float %mp0, %mp1\n")
	b.WriteString("  %each = fadd float %r, %b\n")
	b.WriteString("  %y = call float @trin_soft_mux(float %w, float %pure, float %each)\n")
	b.WriteString("  ret float %y\n")
	b.WriteString("}\n\n")
// also try any fn named loss / kernel
	for _, it := range prog.Items {
		if fn, ok := it.(*ast.FnDef); ok && (fn.Name == "loss" || fn.Name == "kernel" || fn.Name == "soft_kernel") {
			b.WriteString(emitPureFn(fn))
			b.WriteByte('\n')
		}
	}
	return b.String()
}
