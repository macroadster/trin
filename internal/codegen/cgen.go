func (g *gen) emitZipWithN(lam *ast.Lambda, spans []ast.Expr, env string) (string, error) {
	ss := make([]string, len(spans))
	for i, e := range spans {
		s, err := g.emitExpr(e, env)
		if err != nil {
			return "", err
		}
		ss[i] = s
	}
	out := g.fresh("zout")
	items := g.fresh("zit")
	n := g.fresh("zn")
	ix := g.fresh("zi")
	bodyEnv := g.fresh("zenv")
	fmt.Fprintf(g.b, "    int %s = %s.n;\n", n, ss[0])
	for _, s := range ss[1:] {
		fmt.Fprintf(g.b, "    if(%s.n < %s) %s = %s.n;\n", s, n, n, s)
	}
	fmt.Fprintf(g.b, "    trin_val *%s = calloc(%s, sizeof(trin_val));\n", items, n)
	fmt.Fprintf(g.b, "    for(int %s = 0; %s < %s; %s++) {\n", ix, ix, n, ix)
	fmt.Fprintf(g.b, "        trin_env %s; env_init(&%s, &%s);\n", bodyEnv, bodyEnv, env)
	for i, s := range ss {
		fmt.Fprintf(g.b, "        env_set(&%s, \"%s\", %s.items[%s]);\n", bodyEnv, lam.Params[i].Name, s, ix)
	}
	bv, err := g.emitExpr(lam.Body, bodyEnv)
	if err != nil {
		return "", err
	}
	fmt.Fprintf(g.b, "        %s[%s] = %s;\n", items, ix, bv)
	fmt.Fprintf(g.b, "    }\n")
	fmt.Fprintf(g.b, "    trin_val %s = trin_span_own(%s, %s);\n", out, items, n)
	return out, nil
}

