	fmt.Fprintf(g.b, "    trin_val *%s = calloc(%s.n, sizeof(trin_val));\n", items, xs)
	fmt.Fprintf(g.b, "    for(int %s = 0; %s < %s.n; %s++) {\n", ix, ix, xs, ix)
	fmt.Fprintf(g.b, "        trin_env %s; env_init(&%s, &%s);\n", bodyEnv, bodyEnv, env)
