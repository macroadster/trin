func (g *cugen) emitFilterLambda(lam *ast.Lambda, spanExpr ast.Expr, env string) (string, error) {
	xs, err := g.emitExpr(spanExpr, env)
	if err != nil {
		return "", err
	}
	out := g.fresh("fout")
	items := g.fresh("fit")
	count := g.fresh("fc")
	ix := g.fresh("fi")
	bodyEnv := g.fresh("fenv")
	pname := lam.Params[0].Name
	fmt.Fprintf(g.b, "    trin_val *%s = (trin_val*)calloc(%s.n, sizeof(trin_val));\n", items, xs)
	fmt.Fprintf(g.b, "    int %s = 0;\n", count)
	fmt.Fprintf(g.b, "    for(int %s = 0; %s < %s.n; %s++) {\n", ix, ix, xs, ix)
	fmt.Fprintf(g.b, "        trin_env %s; env_init(&%s, &%s);\n", bodyEnv, bodyEnv, env)
	fmt.Fprintf(g.b, "        env_set(&%s, \"%s\", %s.items[%s]);\n", bodyEnv, pname, xs, ix)
	pv, err := g.emitExpr(lam.Body, bodyEnv)
	if err != nil {
		return "", err
	}
	fmt.Fprintf(g.b, "        if(as_f(%s) != 0) { %s[%s++] = %s.items[%s]; }\n", pv, items, count, xs, ix)
	fmt.Fprintf(g.b, "    }\n")
	fmt.Fprintf(g.b, "    trin_val %s = trin_span_own(%s, %s);\n", out, items, count)
	return out, nil
}
