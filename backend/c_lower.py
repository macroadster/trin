"""
Trin → C lowering (v0.2).

Focus:
  - Hello-world style: input name, ternary string select, println
  - Branchless soft mux pattern for unit/f32
  - Hard bit select for strings / control
  - Emits / points at span + trit_gemm kernels (kernels.h)

Not a full compiler — pattern-matches the hello program AST and also
emits reusable C headers for hand-written kernels.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import List, Optional

# Allow running as script from trin/
ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from trin_lang.ast_nodes import (  # noqa: E402
    Binary,
    Block,
    Call,
    Expr,
    ExprStmt,
    FnDef,
    LetStmt,
    Literal,
    Program,
    Ternary,
    Var,
)
from trin_lang.parser import parse_source  # noqa: E402


MUX_HEADER = r"""
/* trin_mux.h — virtual ternary helpers for binary metal */
#ifndef TRIN_MUX_H
#define TRIN_MUX_H

#include <stdio.h>
#include <string.h>

/* Soft unit multiplex: out = g*pure + (1-g)*each  (branchless) */
static inline float trin_soft_mux_f32(float g, float pure, float each) {
    return g * pure + (1.0f - g) * each;
}

/* Hard bit select for floats (compiler may emit CMOV/blend) */
static inline float trin_hard_mux_f32(int bit, float pure, float each) {
    return bit ? pure : each;
}

/* Hard bit select for C strings (pointers; not soft-blendable) */
static inline const char *trin_hard_mux_str(int bit, const char *pure, const char *each) {
    return bit ? pure : each;
}

/*
 * gate | pure | each  on unit:
 *   w==0 -> each (false / return-default)
 *   w==1 -> pure
 *   else -> soft blend
 * For strings, mid weights snap at 0.5.
 */
static inline const char *trin_ternary_str(float gate, const char *pure, const char *each) {
    if (gate >= 1.0f - 1e-6f) return pure;
    if (gate <= 1e-6f) return each;
    return (gate >= 0.5f) ? pure : each;
}

static inline float trin_ternary_f32(float gate, float pure, float each) {
    if (gate >= 1.0f - 1e-6f) return pure;
    if (gate <= 1e-6f) return each;
    return trin_soft_mux_f32(gate, pure, each);
}

#endif
""".lstrip()


def _c_escape(s: str) -> str:
    return (
        s.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\t", "\\t")
    )


def _is_hello_shaped(prog: Program) -> Optional[FnDef]:
    for item in prog.items:
        if isinstance(item, FnDef) and item.name == "main":
            return item
    return None


def _collect_lets(block: Block) -> List[LetStmt]:
    return [s for s in block.stmts if isinstance(s, LetStmt)]


def lower_hello_to_c(prog: Program) -> str:
    """
    Lower examples/hello.trin (and similar) to standalone C.
    Fallback: emit a generic template that still demos the ternary mux.
    """
    main_fn = _is_hello_shaped(prog)
    lines: List[str] = []
    lines.append("/* Generated by Trin C backend v0.1 — virtual ternary on binary */")
    lines.append('#include <stdio.h>')
    lines.append('#include <string.h>')
    lines.append("")
    lines.append(MUX_HEADER.replace("#include <stdio.h>\n#include <string.h>\n\n", ""))
    lines.append("")
    lines.append("int main(void) {")
    lines.append("    char name[256];")
    lines.append("    char pure_msg[512];")
    lines.append("    const char *msg;")
    lines.append("    int gate;")
    lines.append("")

    if main_fn and main_fn.body:
        lets = _collect_lets(main_fn.body)
        # default hello pattern
        prompt = "Enter your name: "
        pure_prefix = "Hello world, "
        each_default = "Hello world, stranger"

        for let in lets:
            if let.name == "name" and isinstance(let.value, Call):
                cal = let.value.callee
                if isinstance(cal, Var) and cal.name == "input" and let.value.args:
                    a0 = let.value.args[0]
                    if isinstance(a0, Literal) and a0.kind == "str":
                        prompt = str(a0.value)
            if let.name == "msg" and isinstance(let.value, Ternary):
                t = let.value
                if isinstance(t.pure, Call) and isinstance(t.pure.callee, Var):
                    if t.pure.callee.name == "str_concat" and len(t.pure.args) >= 1:
                        a0 = t.pure.args[0]
                        if isinstance(a0, Literal) and a0.kind == "str":
                            pure_prefix = str(a0.value)
                if isinstance(t.each, Literal) and t.each.kind == "str":
                    each_default = str(t.each.value)

        lines.append("    /* gate | pure | each  — hard bit from name non-empty */")
        lines.append(f'    printf("{_c_escape(prompt)}");')
        lines.append("    if (!fgets(name, sizeof name, stdin)) {")
        lines.append("        name[0] = '\\0';")
        lines.append("    } else {")
        lines.append("        size_t n = strlen(name);")
        lines.append("        if (n && (name[n-1] == '\\n' || name[n-1] == '\\r')) name[--n] = '\\0';")
        lines.append("        if (n && name[n-1] == '\\r') name[--n] = '\\0';")
        lines.append("    }")
        lines.append("")
        lines.append("    /* (str_len(name) > 0) as bit gate */")
        lines.append("    gate = (int)(strlen(name) > 0);")
        lines.append("")
        lines.append(f'    snprintf(pure_msg, sizeof pure_msg, "%s%s", "{_c_escape(pure_prefix)}", name);')
        lines.append(f'    /* ternary: gate | pure | each */')
        lines.append(
            f'    msg = trin_hard_mux_str(gate, pure_msg, "{_c_escape(each_default)}");'
        )
        lines.append("    puts(msg);")
    else:
        lines.append('    printf("Enter your name: ");')
        lines.append("    if (!fgets(name, sizeof name, stdin)) name[0] = '\\0';")
        lines.append("    else {")
        lines.append("        size_t n = strlen(name);")
        lines.append("        if (n && name[n-1] == '\\n') name[--n] = '\\0';")
        lines.append("    }")
        lines.append("    gate = (int)(strlen(name) > 0);")
        lines.append('    snprintf(pure_msg, sizeof pure_msg, "Hello world, %s", name);')
        lines.append('    msg = trin_hard_mux_str(gate, pure_msg, "Hello world, stranger");')
        lines.append("    puts(msg);")

    lines.append("")
    lines.append("    /* Soft mux demo (dead code sidechannel for AI kernels) */")
    lines.append("    {")
    lines.append("        float g = 0.75f;")
    lines.append("        float y = trin_ternary_f32(g, 1.0f, 0.0f);")
    lines.append('        /* y == 0.75f branchless */')
    lines.append("        (void)y;")
    lines.append("    }")
    lines.append("    return 0;")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def lower_file(path: Path, out: Optional[Path] = None) -> Path:
    src = path.read_text(encoding="utf-8")
    prog = parse_source(src)
    c_src = lower_hello_to_c(prog)
    if out is None:
        out = path.with_suffix(".c")
    out.write_text(c_src, encoding="utf-8")
    # also write headers next to out
    hdr = out.parent / "trin_mux.h"
    hdr.write_text(MUX_HEADER, encoding="utf-8")
    kernels_src = Path(__file__).with_name("kernels.h")
    if kernels_src.exists():
        (out.parent / "kernels.h").write_text(
            kernels_src.read_text(encoding="utf-8"), encoding="utf-8"
        )
    return out


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description="Lower Trin hello-style program to C")
    ap.add_argument("input", type=Path, help=".trin source")
    ap.add_argument("-o", "--output", type=Path, default=None, help="output .c path")
    args = ap.parse_args(argv)
    out = lower_file(args.input, args.output)
    print(f"wrote {out}")
    print(f"wrote {out.parent / 'trin_mux.h'}")
    if (out.parent / "kernels.h").exists():
        print(f"wrote {out.parent / 'kernels.h'} (span + trit_gemm)")
    print(f"compile: cc -O2 -o hello {out}")
    print(f"kernels: cc -O2 -o kernel_demo backend/kernel_demo.c  # from trin/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
